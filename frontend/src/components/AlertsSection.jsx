import React from 'react';
import { AlertTriangle, CheckCircle2, Clock, MapPin, ShieldAlert, ShieldCheck } from 'lucide-react';

export default function AlertsSection({ alerts, onResolveAlert }) {
  const unresolvedAlerts = alerts.filter(a => !a.resolved);
  const resolvedAlerts = alerts.filter(a => a.resolved);

  return (
    <section className="alerts-section" id="alerts">
      <div className="section-heading">
        <div className="badge">
          <AlertTriangle size={14} /> LIVE RISK MONITORING
        </div>
        <h2>
          Active Operational <span>Risk Alerts</span>
        </h2>
        <p>
          Real-time risk warnings generated by ManganeseAI to alert ground operations, logistic planners, and survey crews regarding production shortfalls or climate disruptions.
        </p>
      </div>

      <div className="alerts-grid">
        {alerts && alerts.length > 0 ? (
          alerts.map((alert) => {
            const severityClass = `severity-${(alert.severity || 'medium').toLowerCase()}`;
            const isResolved = alert.resolved;

            return (
              <div 
                key={alert.id} 
                className={`alert-item ${severityClass}`} 
                style={{ opacity: isResolved ? 0.6 : 1 }}
              >
                <div className="alert-info">
                  <div style={{ display: 'flex', alignItems: 'center', gap: '10px', marginBottom: '4px' }}>
                    <span className={`status-badge ${(alert.severity || 'medium').toLowerCase()}`}>
                      {(alert.severity || 'medium').toUpperCase()} SEVERITY
                    </span>
                    <span style={{ fontSize: '12px', color: '#64748b', display: 'flex', alignItems: 'center', gap: '4px' }}>
                      <MapPin size={12} /> {alert.site || 'Bamebari Site'}
                    </span>
                    {alert.eta && alert.eta !== '—' && (
                      <span style={{ fontSize: '12px', color: '#94a3b8', display: 'flex', alignItems: 'center', gap: '4px' }}>
                        <Clock size={12} /> ETA: {alert.eta}
                      </span>
                    )}
                  </div>

                  <h4 style={{ fontFamily: 'Outfit', marginTop: '6px' }}>
                    {alert.issue || 'Monsoon disruption affecting overburden transport'}
                  </h4>

                  <p style={{ fontSize: '12px', color: '#94a3b8', marginTop: '4px' }}>
                    Registered: {alert.createdAt ? new Date(alert.createdAt).toLocaleString() : 'Recent'}
                  </p>
                </div>

                <div>
                  {isResolved ? (
                    <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#10b981', fontSize: '13px', fontWeight: 'bold', padding: '8px 16px', background: 'rgba(16,185,129,0.1)', borderRadius: '8px' }}>
                      <CheckCircle2 size={16} /> Resolved
                    </div>
                  ) : (
                    <button 
                      className="resolve-btn"
                      onClick={() => onResolveAlert(alert.id)}
                    >
                      Resolve Alert
                    </button>
                  )}
                </div>
              </div>
            );
          })
        ) : (
          <div style={{ padding: '32px', textAlign: 'center', background: 'var(--bg-card)', border: '1px solid var(--border-subtle)', borderRadius: '16px', color: '#94a3b8' }}>
            <ShieldCheck size={40} style={{ color: '#10b981', marginBottom: '12px' }} />
            <h3>No Active High Severity Alerts</h3>
            <p style={{ fontSize: '13px', color: '#64748b', marginTop: '4px' }}>
              All monitored manganese extraction sites are currently operating within normal parameters.
            </p>
          </div>
        )}
      </div>
    </section>
  );
}
